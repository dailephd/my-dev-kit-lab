import {
  assertLogicalPath,
  buildRenderContext,
  canonicalText,
  compareLogicalPaths,
  exportedSymbolOf,
  patternCommentLines,
  SyntheticRepositoryRenderError,
} from "./renderShared.js";
import type { RenderContext, RenderedFile } from "./renderShared.js";
import type { PlannedSourceModule, PlannedTestFile, SyntheticRepositoryPlanV1 } from "./types.js";

const PY_PROJECT_TOML = canonicalText([
  "[project]",
  'name = "synthetic-repository"',
  'version = "0.0.0"',
  "",
  "[tool.pytest.ini_options]",
  'pythonpath = ["src"]',
  'testpaths = ["tests"]',
]);

/**
 * Dotted module name of a planned source path. Source modules live under `src/`, which is the Python
 * import root (`pythonpath = ["src"]`); directories are implicit namespace packages, so no `__init__.py`
 * support files are needed and none can inflate the planned source-file count.
 */
export function pythonModuleName(logicalPath: string): string {
  if (!logicalPath.startsWith("src/") || !logicalPath.endsWith(".py")) {
    throw new SyntheticRepositoryRenderError([`python source path ${JSON.stringify(logicalPath)} must be under src/ and end in .py.`]);
  }
  return logicalPath.slice("src/".length, -".py".length).split("/").join(".");
}

function renderModule(module: PlannedSourceModule, context: RenderContext, pathOf: (moduleId: string) => string): string {
  const dependencies = (context.importsByModule.get(module.moduleId) ?? []).map((target) => ({
    symbol: exportedSymbolOf(context, target),
    moduleName: pythonModuleName(pathOf(target)),
  }));
  const lines: string[] = [`"""Synthetic module ${module.moduleId} (dependency level ${module.level}). Generated by my-dev-kit-lab."""`];
  for (const dependency of dependencies) lines.push(`from ${dependency.moduleName} import ${dependency.symbol.name}`);
  for (const pattern of context.patternsByModule.get(module.moduleId) ?? []) {
    lines.push("", ...patternCommentLines(pattern, "#"));
  }
  (context.symbolsByModule.get(module.moduleId) ?? []).forEach((symbol, position) => {
    lines.push(
      "",
      "",
      `def ${symbol.name}(input_value: int) -> int:`,
      `    """Synthetic symbol ${symbol.name} of ${module.moduleId}."""`,
      `    total = input_value + ${symbol.ordinal}`
    );
    if (position === 0) {
      for (const dependency of dependencies) lines.push(`    total += ${dependency.symbol.name}(total) % 7`);
    }
    lines.push("    return total");
  });
  return canonicalText(lines);
}

function renderTest(test: PlannedTestFile, context: RenderContext, pathOf: (moduleId: string) => string): string {
  const names = test.targetSymbolIds.map((symbolId) => (context.symbolById.get(symbolId) as { name: string }).name);
  return canonicalText([
    `from ${pythonModuleName(pathOf(test.targetModuleId))} import ${names.join(", ")}`,
    "",
    "",
    `def test_case_${test.testId.slice("test_".length)}():`,
    ...names.map((name) => `    assert isinstance(${name}(1), int)`),
  ]);
}

/** Deterministic projection of a Python plan into files, sorted by logical path. */
export function renderPythonRepository(plan: SyntheticRepositoryPlanV1): RenderedFile[] {
  const context = buildRenderContext(plan);
  const pathOf = (moduleId: string): string => (context.moduleById.get(moduleId) as PlannedSourceModule).path;
  const files: RenderedFile[] = [];
  for (const module of plan.modules) {
    assertLogicalPath(module.path, ".py");
    files.push({ path: module.path, role: "source", language: "python", content: renderModule(module, context, pathOf) });
  }
  for (const test of plan.testFiles) {
    assertLogicalPath(test.path, ".py");
    files.push({ path: test.path, role: "test", language: "python", content: renderTest(test, context, pathOf) });
  }
  files.push({ path: "pyproject.toml", role: "support", content: PY_PROJECT_TOML });
  return files.sort(compareLogicalPaths);
}
