import {
  assertLogicalPath,
  buildRenderContext,
  canonicalText,
  compareLogicalPaths,
  exportedSymbolOf,
  patternCommentLines,
  relativeSpecifier,
} from "./renderShared.js";
import type { RenderContext, RenderedFile } from "./renderShared.js";
import type { PlannedSourceModule, PlannedTestFile, SyntheticRepositoryPlanV1 } from "./types.js";

const TS_PACKAGE_JSON = canonicalText([
  "{",
  '  "name": "synthetic-repository",',
  '  "version": "0.0.0",',
  '  "private": true,',
  '  "type": "module",',
  '  "scripts": {',
  '    "test": "vitest run"',
  "  }",
  "}",
]);

const TS_CONFIG_JSON = canonicalText([
  "{",
  '  "compilerOptions": {',
  '    "target": "ES2022",',
  '    "module": "NodeNext",',
  '    "moduleResolution": "NodeNext",',
  '    "strict": true,',
  '    "noEmit": true,',
  '    "skipLibCheck": true',
  "  },",
  '  "include": ["src", "tests"]',
  "}",
]);

/** `.ts` logical path to the NodeNext `.js` import specifier. */
function importSpecifier(fromPath: string, toPath: string): string {
  return relativeSpecifier(fromPath, toPath).replace(/\.ts$/, ".js");
}

function renderModule(module: PlannedSourceModule, context: RenderContext, pathOf: (moduleId: string) => string): string {
  const lines: string[] = [`// Synthetic module ${module.moduleId} (dependency level ${module.level}). Generated by my-dev-kit-lab.`];
  const dependencies = (context.importsByModule.get(module.moduleId) ?? []).map((target) => ({
    target,
    symbol: exportedSymbolOf(context, target),
  }));
  for (const dependency of dependencies) {
    lines.push(`import { ${dependency.symbol.name} } from "${importSpecifier(module.path, pathOf(dependency.target))}";`);
  }
  for (const pattern of context.patternsByModule.get(module.moduleId) ?? []) {
    lines.push("", ...patternCommentLines(pattern, "//"));
  }
  (context.symbolsByModule.get(module.moduleId) ?? []).forEach((symbol, position) => {
    lines.push(
      "",
      `/** Synthetic symbol ${symbol.name} of ${module.moduleId}. */`,
      `export function ${symbol.name}(input: number): number {`,
      `  let total = input + ${symbol.ordinal};`
    );
    if (position === 0) {
      for (const dependency of dependencies) lines.push(`  total += ${dependency.symbol.name}(total) % 7;`);
    }
    lines.push("  return total;", "}");
  });
  return canonicalText(lines);
}

function renderTest(test: PlannedTestFile, context: RenderContext): string {
  const target = context.moduleById.get(test.targetModuleId) as PlannedSourceModule;
  const names = test.targetSymbolIds.map((symbolId) => (context.symbolById.get(symbolId) as { name: string }).name);
  return canonicalText([
    'import { describe, expect, it } from "vitest";',
    `import { ${names.join(", ")} } from "${importSpecifier(test.path, target.path)}";`,
    "",
    `describe("${test.testId}", () => {`,
    `  it("exercises ${target.moduleId}", () => {`,
    ...names.map((name) => `    expect(typeof ${name}(1)).toBe("number");`),
    "  });",
    "});",
  ]);
}

/** Deterministic projection of a TypeScript plan into files, sorted by logical path. */
export function renderTypeScriptRepository(plan: SyntheticRepositoryPlanV1): RenderedFile[] {
  const context = buildRenderContext(plan);
  const pathOf = (moduleId: string): string => (context.moduleById.get(moduleId) as PlannedSourceModule).path;
  const files: RenderedFile[] = [];
  for (const module of plan.modules) {
    assertLogicalPath(module.path, ".ts");
    files.push({ path: module.path, role: "source", language: "typescript", content: renderModule(module, context, pathOf) });
  }
  for (const test of plan.testFiles) {
    assertLogicalPath(test.path, ".test.ts");
    files.push({ path: test.path, role: "test", language: "typescript", content: renderTest(test, context) });
  }
  files.push({ path: "package.json", role: "support", content: TS_PACKAGE_JSON });
  files.push({ path: "tsconfig.json", role: "support", content: TS_CONFIG_JSON });
  return files.sort(compareLogicalPaths);
}
